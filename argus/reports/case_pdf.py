"""PDFs of a case's people: one person's profile, and the case's network of relationships.

For editors, lawyers and courts, who need something they can read, file and cite. Each PDF:

* is marked **CONFIDENTIAL: contains personal data** on every page, with the case, the date and
  page numbers;
* can include the link chart as the investigator sees it (a picture the browser sends, checked and
  re-drawn as a clean PNG so nothing else rides along);
* says plainly that relationships marked *likely* or *possible* are not established facts, and
  that name matches are possibilities;
* leaves protected people (for example, children) unnamed, as everywhere else in Argus.
"""

from __future__ import annotations

import io
from collections.abc import Callable
from datetime import datetime, timezone
from typing import Any

from PIL import Image as PILImage
from reportlab.lib import colors
from reportlab.lib.pagesizes import A4
from reportlab.lib.units import mm
from reportlab.platypus import Image, Paragraph, SimpleDocTemplate, Spacer, Table, TableStyle

from argus.reports.pdf import MARGIN, MUTED, RULE, SOFT, _Fonts, _register_fonts, _styles, esc

PAGE_W, PAGE_H = A4
ACCENT = colors.HexColor("#4f5bd5")
CONFIDENCE_COLOUR = {"confirmed": "#15803d", "likely": "#4f5bd5", "possible": "#b45309", "recorded": "#6b7280"}
MAX_CHART_BYTES = 8 * 1024 * 1024
RANGE = " \u2013 "  # an en dash between dates
CAVEAT = ("Relationships marked likely or possible, and matches on a name alone, are leads, not established facts. "
          "Check each against its source before relying on it.")  # fmt: skip


class ChartError(ValueError):
    pass


def clean_chart(png: bytes) -> bytes:
    """The link chart picture from the browser, checked and re-drawn as a plain PNG (no metadata)."""
    if len(png) > MAX_CHART_BYTES:
        raise ChartError("The chart picture is too large")
    try:
        with PILImage.open(io.BytesIO(png)) as img:
            if img.format != "PNG" or img.width * img.height > 40_000_000:
                raise ChartError("The chart must be a PNG picture of a reasonable size")
            img.load()
            out = io.BytesIO()
            img.convert("RGB").save(out, format="PNG", optimize=True)
            return out.getvalue()
    except (OSError, PILImage.DecompressionBombError) as exc:
        raise ChartError("The chart picture could not be read") from exc


def _frame(case_title: str, kind: str) -> Callable[[Any, Any], None]:
    stamp = datetime.now(timezone.utc).strftime("%d %b %Y %H:%M UTC")

    def draw(c: Any, doc: Any) -> None:
        c.saveState()
        c.setFillColor(colors.HexColor("#b91c1c"))
        c.setFont(_Fonts.bold, 7.5)
        c.drawString(MARGIN, PAGE_H - 11 * mm, "CONFIDENTIAL: contains personal data")
        c.setFillColor(MUTED)
        c.setFont(_Fonts.regular, 7.5)
        c.drawRightString(PAGE_W - MARGIN, PAGE_H - 11 * mm, f"{kind} · {case_title[:70]}")
        c.setStrokeColor(RULE)
        c.line(MARGIN, 14 * mm, PAGE_W - MARGIN, 14 * mm)
        c.drawString(MARGIN, 10 * mm, f"Generated by Argus · {stamp}")
        c.drawRightString(PAGE_W - MARGIN, 10 * mm, f"Page {doc.page}")
        c.restoreState()

    return draw


def _doc(buffer: io.BytesIO, title: str) -> SimpleDocTemplate:
    return SimpleDocTemplate(buffer, pagesize=A4, leftMargin=MARGIN, rightMargin=MARGIN, topMargin=MARGIN + 4 * mm,
                             bottomMargin=MARGIN, title=title, author="Argus", subject="Confidential")  # fmt: skip


def _table(rows: list[list[Any]], widths: list[float], s: dict[str, Any]) -> Table:
    t = Table([[Paragraph(str(c), s["cellb" if i == 0 else "cell"]) for c in row] for i, row in enumerate(rows)],
              colWidths=widths, repeatRows=1)  # fmt: skip
    t.setStyle(TableStyle([("BACKGROUND", (0, 0), (-1, 0), SOFT), ("LINEBELOW", (0, 0), (-1, -1), 0.4, RULE),
                           ("VALIGN", (0, 0), (-1, -1), "TOP"), ("TOPPADDING", (0, 0), (-1, -1), 3),
                           ("BOTTOMPADDING", (0, 0), (-1, -1), 3)]))  # fmt: skip
    return t


def _conf(value: str) -> str:
    return f'<font color="{CONFIDENCE_COLOUR.get(value, "#6b7280")}">{esc(value)}</font>'


def _chart(png: bytes | None, width: float, max_height: float) -> list[Any]:
    if not png:
        return []
    with PILImage.open(io.BytesIO(png)) as img:
        w, h = img.size
    scale = min(width / w, max_height / h)
    return [Image(io.BytesIO(png), width=w * scale, height=h * scale), Spacer(1, 4 * mm)]


def _relationship_rows(rows: list[dict[str, Any]], name: str) -> list[list[str]]:
    out = [["Relationship", "How sure", "When", "How it was found"]]
    for r in rows:
        if r.get("outgoing") is False and not r.get("symmetric"):
            text = f"<b>{esc(r['other'])}</b> {esc(r['text'])} {esc(name)}"
        else:
            text = f"{esc(r['text'])} <b>{esc(r['other'])}</b>"
        when = RANGE.join(x for x in (r.get("since"), r.get("until")) if x) or ""
        out.append([text, _conf(r.get("confidence", "")), esc(when), esc(r.get("why") or "")])
    return out


def profile_pdf(profile: dict[str, Any], case: dict[str, Any], chart_png: bytes | None = None) -> bytes:
    """One person's (or organisation's) profile as a PDF."""
    _register_fonts()
    s = _styles(ACCENT)
    buffer = io.BytesIO()
    doc = _doc(buffer, f"Profile: {profile['name']}")
    width = doc.width
    story: list[Any] = [Paragraph("PROFILE", s["kicker"]), Paragraph(esc(profile["name"]), s["H1"]),
                        Paragraph(esc(f"{profile['type']} · case: {case['title']}"), s["muted"]),
                        Paragraph(esc(CAVEAT), s["muted"]), Spacer(1, 3 * mm)]  # fmt: skip
    if profile.get("protected"):
        story.append(Paragraph(esc(profile.get("message", "")), s["body"]))
    else:
        if profile.get("attributes"):
            story += [Paragraph("Details", s["H2"]),
                      _table([["Detail", "Value"], *[[esc(k), esc(v)] for k, v in profile["attributes"].items()]],
                             [45 * mm, width - 45 * mm], s)]  # fmt: skip
        if profile.get("notes"):
            story += [Paragraph("Notes", s["H2"]), Paragraph(esc(profile["notes"]).replace("\n", "<br/>"), s["body"])]
        n = profile.get("network") or {}
        roles = ", ".join(
            x for x, on in (("key person", n.get("key_person")), ("go-between", n.get("go_between"))) if on
        )
        story += [Paragraph("Place in the network", s["H2"]),
                  Paragraph(esc(f"{n.get('connections', 0)} relationships"
                                + (f"; group {n['group']} of {n.get('group_size')}" if n.get("group") else "")
                                + (f"; {roles}" if roles else "")), s["body"])]  # fmt: skip
        story += _chart(chart_png, width, 110 * mm)
        for title, key in (("Relationships", "relationships"), ("Accounts and contacts", "identifiers")):
            if profile.get(key):
                story += [Paragraph(title, s["H2"]),
                          _table(_relationship_rows(profile[key], profile["name"]),
                                 [width * 0.42, width * 0.13, width * 0.17, width * 0.28], s)]  # fmt: skip
        if profile.get("places"):
            story += [
                Paragraph("Places", s["H2"]),
                *[Paragraph(esc(f"{p['other']} ({p['text']})"), s["body"]) for p in profile["places"]],
            ]
        for scan in profile.get("scans") or []:
            block: list[Any] = [Paragraph(esc(f"What the scan of {scan['scan']} found"), s["H2"])]
            if scan.get("facts"):
                block.append(_table([["Fact", "Value"], *[[esc(k.replace("_", " ")), esc(v)] for k, v in scan["facts"].items()]],
                                    [45 * mm, width - 45 * mm], s))  # fmt: skip
            for x in scan.get("sanctions") or []:
                line = f"Similar name on {x.get('list')}: {x.get('name')}"
                if x.get("conflicts"):
                    line += f". Probably a different person: {'; '.join(x['conflicts'])}"
                block.append(Paragraph(esc(line), s["body"]))
            block += [Paragraph(esc(f"Named in the Offshore Leaks: {x.get('name')} {x.get('url') or ''}"), s["body"])
                      for x in scan.get("offshore_leaks") or []]  # fmt: skip
            if scan.get("appointments"):
                block.append(_table([["Role", "Company", "From", "To"],
                                     *[[esc(a.get("role")), esc(a.get("company")), esc(a.get("from") or ""),
                                        esc(a.get("to") or "")] for a in scan["appointments"]]],
                                    [width * 0.3, width * 0.4, width * 0.15, width * 0.15], s))  # fmt: skip
            story += block
        if profile.get("timeline"):
            story += [Paragraph("Timeline", s["H2"]),
                      _table([["Date", "What happened", "Source"],
                              *[[esc(t["date"]), esc(t["text"]), esc(t["source"])] for t in profile["timeline"]]],
                             [25 * mm, width - 55 * mm, 30 * mm], s)]  # fmt: skip
        if profile.get("mentions"):
            story.append(Paragraph(f"Mentioned in ({len(profile['mentions'])})", s["H2"]))
            for m in profile["mentions"]:
                story.append(Paragraph(f"<b>{esc(m['kind'])}: {esc(m.get('title') or '')}</b> "
                                       f"<font color='#6b7280'>{esc((m.get('when') or '')[:10])}</font>", s["body"]))  # fmt: skip
                story += [Paragraph(f"“{esc(p)}”", s["muted"]) for p in m["passages"]]
    doc.build(story, onFirstPage=_frame(case["title"], "Profile"), onLaterPages=_frame(case["title"], "Profile"))
    return buffer.getvalue()


def network_pdf(network: dict[str, Any], case: dict[str, Any], chart_png: bytes | None = None,
                as_of: str | None = None) -> bytes:  # fmt: skip
    """The case's network: the chart, its key people, go-betweens and groups, and every relationship."""
    _register_fonts()
    s = _styles(ACCENT)
    buffer = io.BytesIO()
    doc = _doc(buffer, f"Network: {case['title']}")
    width = doc.width
    nodes = {n["id"]: n for n in network["nodes"]}
    a = network["analysis"]
    story: list[Any] = [Paragraph("NETWORK OF RELATIONSHIPS", s["kicker"]), Paragraph(esc(case["title"]), s["H1"]),
                        Paragraph(esc(case.get("purpose") or ""), s["muted"]),
                        Paragraph(esc(f"{len(network['nodes'])} people and organisations, {len(network['edges'])} relationships"
                                      + (f"; the network as it stood on {as_of}" if as_of else "")), s["body"]),
                        Paragraph(esc(CAVEAT), s["muted"]), Spacer(1, 3 * mm)]  # fmt: skip
    story += _chart(chart_png, width, 150 * mm)
    if a.get("key_people"):
        story += [
            Paragraph("Most connected", s["H2"]),
            *[Paragraph(esc(f"{p['label']}: {p['connections']} relationships"), s["body"]) for p in a["key_people"]],
        ]
    if a.get("bridges"):
        story += [Paragraph("Go-betweens", s["H2"]),
                  Paragraph("They connect groups that are otherwise apart.", s["muted"]),
                  *[Paragraph(esc(f"{p['label']}: links groups {' and '.join(str(g + 1) for g in p['groups'])}"), s["body"])
                    for p in a["bridges"]]]  # fmt: skip
    if a.get("clusters"):
        story += [Paragraph("Groups", s["H2"]),
                  *[Paragraph(esc(f"Group {c['id'] + 1}: " + ", ".join(nodes[m]["label"] for m in c["members"] if m in nodes)),
                              s["body"]) for c in a["clusters"]]]  # fmt: skip
    rows = [["From", "Relationship", "To", "How sure", "When", "How it was found"]]
    for e in sorted(network["edges"], key=lambda e: (e["group"], nodes.get(e["from"], {}).get("label", ""))):
        when = RANGE.join(x for x in (e.get("since"), e.get("until")) if x)
        rows.append([esc(nodes.get(e["from"], {}).get("label", "?")), esc(e["text"]), esc(nodes.get(e["to"], {}).get("label", "?")),
                     _conf(e["confidence"]), esc(when), esc(e.get("why") or "")])  # fmt: skip
    if len(rows) > 1:
        story += [
            Paragraph("Every relationship", s["H2"]),
            _table(rows, [width * 0.18, width * 0.2, width * 0.18, width * 0.1, width * 0.12, width * 0.22], s),
        ]
    if a.get("isolated"):
        story += [Paragraph("Not connected yet", s["H2"]),
                  Paragraph(esc(", ".join(p["label"] for p in a["isolated"])), s["body"])]  # fmt: skip
    doc.build(story, onFirstPage=_frame(case["title"], "Network"), onLaterPages=_frame(case["title"], "Network"))
    return buffer.getvalue()
